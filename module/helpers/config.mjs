/**
 * Configuration des Active Effects
 *
 * Chaque entrée :
 *
 * path : chemin Foundry de la valeur modifiée
 *
 * label : traduction affichée
 *
 * category :
 * - resource
 * - stats
 * - mastery
 * - combat
 * - resistance
 *
 * type :
 * - number
 *
 */

SHINZO.activeEffectChanges = {};



const EFFECT_MODES = [

    CONST.ACTIVE_EFFECT_MODES.ADD,

    CONST.ACTIVE_EFFECT_MODES.MULTIPLY,

    CONST.ACTIVE_EFFECT_MODES.OVERRIDE

];



function createEffect(label, abbreviation, category){

    return {

        label,

        abbreviation,

        category,

        type:"number",

        modes:EFFECT_MODES

    };

}



